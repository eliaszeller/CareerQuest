import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('John Business and concrete roadmap checkpoints', async ({ page }, info) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Start your quest' }).click();
  await page.getByRole('button', { name: /Recommended Build my character/ }).click();
  await page.getByLabel(/what should we call/i).fill('Alex');
  await page.getByRole('radio', { name: 'High school' }).check();
  await page.getByRole('button', { name: /04 Review/ }).click();
  await page.getByRole('checkbox', { name: /reviewed my character/ }).check();
  await page.getByRole('button', { name: /Confirm my character/ }).click();
  await expect(page.getByRole('heading', { name: 'John Business' })).toBeVisible();
  await expect(page.getByRole('group', { name: 'Character gender presentation' })).toHaveCount(0);
  expect((await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([]);
  await page.screenshot({ path: info.outputPath('john-character.png'), fullPage: true });
  await page.getByRole('button', { name: /Use this character/ }).click();
  await page.getByLabel('Custom target role').fill('Teacher');
  await page.getByRole('button', { name: /Generate my 3 paths/ }).click();
  await page.getByRole('button', { name: /Continue to simulation/ }).click();
  await page.getByRole('button', { name: 'View roadmap →', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your next 90 days.' })).toBeVisible();
  await expect(page.getByText('Meet a school counselor or trusted advisor')).toBeVisible();
  await expect(page.getByRole('checkbox')).toHaveCount(12);
  await page.getByRole('checkbox').first().check();
  await expect(page.getByRole('status')).toContainText('1 / 12');
  await page.getByRole('button', { name: /Back to simulation/ }).click();
  await page.getByRole('button', { name: 'View roadmap →', exact: true }).click();
  await expect(page.getByRole('checkbox').first()).toBeChecked();
  await page.getByRole('link', { name: /02 Practice/ }).click();
  await expect(page.locator('#milestone-1')).toBeInViewport();
  await page.evaluate(() => window.scrollTo(0, 0));
  expect((await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('retro-roadmap.png'), fullPage: true });
});
